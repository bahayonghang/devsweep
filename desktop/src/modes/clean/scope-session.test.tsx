import { useState } from "react";
import { act, render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";
import { fixtureBridge } from "../../api/fixture-bridge";
import { decodeScanReport } from "../../api/contract";
import scanJson from "../../api/fixtures/scan-report.json";
import scanReplays from "../../api/fixtures/clean/scan-advisory-replays.json";
import type { DesktopBridge } from "../../api/bridge";
import type { DesktopScanResult, ScanOptions } from "../../api/types.gen";
import { OperationCoordinator } from "../../state/operation-coordinator";
import { CleanSessionProvider } from "./CleanSession";
import { CleanWorkbench } from "./CleanWorkbench";

const base = decodeScanReport(scanJson);
const reportFor = (options: ScanOptions) => ({ ...base, plan: { ...base.plan, targets: base.plan.targets.filter(target => target.scope.type === "global" ? options.include_global : options.include_projects).map(target => ({ ...target, selected_by_default: false })) } });
const completedScan = vi.fn(async (scanId: string, options: ScanOptions): Promise<DesktopScanResult> => ({ type: "completed", scan_id: scanId, report: reportFor(options) }));
function Harness({ bridge, coordinator = new OperationCoordinator() }: { bridge: DesktopBridge; coordinator?: OperationCoordinator }) {
  const [shown, setShown] = useState(true);
  return <CleanSessionProvider bridge={bridge}><button onClick={() => setShown(!shown)}>Toggle route</button>{shown && <CleanWorkbench bridge={bridge} coordinator={coordinator} locale="en" />}</CleanSessionProvider>;
}
const roots = { version: 1 as const, roots: ["C:/work/app"], suggestions: [] };
describe("independent scope sessions", () => {
  it("allows exact global-only scanning with an unavailable roots store", async () => {
    const scanStart = vi.fn(completedScan);
    render(<CleanWorkbench bridge={{ ...fixtureBridge, scanStart, cleanScanPreferencesGet: async () => { throw new Error("settings locked"); } }} coordinator={new OperationCoordinator()} locale="en" />);
    const user = userEvent.setup();
    await user.click(screen.getByRole("button", { name: "Scan global caches" }));
    await screen.findByRole("button", { name: "Review global targets" });
    expect(scanStart).toHaveBeenCalledWith(expect.any(String), { include_projects: false, include_global: true, roots: [] }, expect.any(Function), expect.any(Function));
    expect(screen.getByRole("button", { name: "Scan project artifacts" })).toBeDisabled();
  });
  it("retains separate reports and clears only project authority on a root edit", async () => {
    const scanStart = vi.fn(completedScan);
    render(<CleanWorkbench bridge={{ ...fixtureBridge, scanStart, cleanScanPreferencesGet: async () => roots }} coordinator={new OperationCoordinator()} locale="en" />);
    const user = userEvent.setup();
    await user.click(screen.getByRole("button", { name: "Scan global caches" }));
    await screen.findByRole("button", { name: "Review global targets" });
    await user.click(screen.getByRole("button", { name: "Scan project artifacts" }));
    await screen.findByRole("button", { name: "Review targets" });
    expect(scanStart.mock.calls[1][1]).toEqual({ include_projects: true, include_global: false, roots: ["C:/work/app"] });
    await user.click(screen.getByText("Project folders (1)"));
    await user.click(screen.getByRole("button", { name: "Remove C:/work/app" }));
    expect(screen.getByRole("button", { name: "Review global targets" })).toBeInTheDocument();
    expect(screen.queryByRole("button", { name: "Review targets" })).not.toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Scan project artifacts" })).toBeDisabled();
  });
  it("single-flights scopes and accepts the completed terminal after cancellation is requested", async () => {
    let finish!: (value: DesktopScanResult) => void;
    const scanStart = vi.fn<DesktopBridge["scanStart"]>(() => new Promise<DesktopScanResult>(resolve => { finish = resolve; }));
    const scanCancel = vi.fn(async () => undefined);
    render(<CleanWorkbench bridge={{ ...fixtureBridge, scanStart, scanCancel }} coordinator={new OperationCoordinator()} locale="en" />);
    const user = userEvent.setup();
    await user.click(screen.getByRole("button", { name: "Scan global caches" }));
    expect(screen.getByRole("button", { name: "Scan project artifacts" })).toBeDisabled();
    await user.click(screen.getByRole("button", { name: "Scan project artifacts" }));
    await user.click(screen.getByRole("button", { name: "Cancel" }));
    await act(async () => finish({ type: "completed", scan_id: scanStart.mock.calls[0][0], report: decodeScanReport(scanReplays.global.report) }));
    expect(scanStart).toHaveBeenCalledTimes(1);
    expect(scanCancel).toHaveBeenCalledTimes(1);
    expect(screen.getByRole("button", { name: "Review global targets" })).toBeInTheDocument();
    expect(screen.queryByText("Scan canceled. Results stay non-selectable.")).not.toBeInTheDocument();
  });
  it("keeps a failed-save threshold in the retained session across route changes", async () => {
    const save = vi.fn(async () => { throw new Error("store locked"); });
    render(<Harness bridge={{ ...fixtureBridge, cleanAdvisoryPreferencesGet: async () => ({ version: 1, threshold_bytes: 5 * 1024 ** 3 }), cleanAdvisoryPreferencesSet: save }} />);
    const user = userEvent.setup();
    await user.click(screen.getByText("Capacity warning: 5 GiB"));
    const field = screen.getByRole("spinbutton");
    await user.clear(field); await user.type(field, "8");
    await user.click(screen.getByRole("button", { name: "Save threshold" }));
    expect(await screen.findByText(/Threshold is session-only/)).toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Toggle route" }));
    await user.click(screen.getByRole("button", { name: "Toggle route" }));
    expect(screen.getByText("Capacity warning: 8 GiB")).toBeInTheDocument();
    await user.click(screen.getByText("Capacity warning: 8 GiB"));
    expect(screen.getByRole("spinbutton")).toHaveValue(8);
    expect(save).toHaveBeenCalledExactlyOnceWith(8);
  });
  it("rejects invalid thresholds without changing selection or calling persistence", async () => {
    const save = vi.fn();
    render(<CleanWorkbench bridge={{ ...fixtureBridge, scanStart: completedScan, cleanAdvisoryPreferencesSet: save }} coordinator={new OperationCoordinator()} locale="en" />);
    const user = userEvent.setup();
    await waitFor(() => expect(screen.getByRole("button", { name: "Scan project artifacts" })).toBeEnabled());
    await user.click(screen.getByRole("button", { name: "Scan project artifacts" }));
    await user.click(await screen.findByRole("button", { name: "Review targets" }));
    await user.click(screen.getByRole("checkbox", { name: "Select C:/work/app/target" }));
    await user.click(screen.getByRole("button", { name: "Back to cleanup" }));
    await user.click(screen.getByText(/Capacity warning:/));
    await user.clear(screen.getByRole("spinbutton")); await user.type(screen.getByRole("spinbutton"), "0.5");
    await user.click(screen.getByRole("button", { name: "Save threshold" }));
    expect(within(screen.getByRole("region", { name: "Project artifacts" })).getByRole("alert")).toHaveTextContent("Enter a whole number");
    expect(save).not.toHaveBeenCalled();
    expect(screen.getByRole("button", { name: "Clean 500.0 MiB" })).toBeInTheDocument();
  });
  it("retains the live preview digest and selection when a valid warning threshold changes", async () => {
    const planDryRun = vi.fn(fixtureBridge.planDryRun);
    const planExecute = vi.fn();
    const save = vi.fn(async (value: number) => ({ version: 1 as const, threshold_bytes: value * 1024 ** 3 }));
    render(<CleanWorkbench bridge={{ ...fixtureBridge, scanStart: completedScan, planDryRun, planExecute, cleanAdvisoryPreferencesSet: save }} coordinator={new OperationCoordinator()} locale="en" />);
    const user = userEvent.setup();
    await waitFor(() => expect(screen.getByRole("button", { name: "Scan project artifacts" })).toBeEnabled());
    await user.click(screen.getByRole("button", { name: "Scan project artifacts" }));
    await user.click(await screen.findByRole("button", { name: "Review targets" }));
    await user.click(screen.getByRole("checkbox", { name: "Select C:/work/app/target" }));
    await user.click(screen.getByRole("button", { name: "Review dry run" }));
    await screen.findByText("Dry-run preview");
    const digest = document.querySelector(".digest-line")!.textContent;
    await user.click(screen.getByRole("button", { name: "Back to cleanup" }));
    await user.click(screen.getByText(/Capacity warning:/));
    await user.clear(screen.getByRole("spinbutton")); await user.type(screen.getByRole("spinbutton"), "3");
    await user.click(screen.getByRole("button", { name: "Save threshold" }));
    await user.click(screen.getByRole("button", { name: "Review targets" }));
    expect(document.querySelector(".digest-line")!.textContent).toBe(digest);
    expect(screen.getByText("Selected 1")).toBeInTheDocument();
    expect(planDryRun).toHaveBeenCalledTimes(1);
    expect(planExecute).not.toHaveBeenCalled();
    expect(save).toHaveBeenCalledExactlyOnceWith(3);
  });
});
